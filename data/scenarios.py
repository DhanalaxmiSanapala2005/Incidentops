def S(id, name, service, category, desc, alerts, metrics, logs, deploys, fix, expect,
      health="degraded", version=None, replicas=2, config=None, flags=None, chaos=None):
    return dict(id=id, name=name, service=service, category=category, description=desc,
                alerts=[dict(metric=m, value=v, minutes_ago=a) for m, v, a in alerts],
                metrics={**BASELINE, **metrics}, logs=logs,
                deployments=[dict(version=v, minutes_ago=a, status=s) for v, a, s in deploys],
                fix=fix, expect=expect, health=health, version=version or deploys[0][0],
                replicas=replicas, config=config or {"cache.ttl_seconds": 300},
                flags=flags or {}, chaos=chaos or {})


